// `exclude`: sentences to avoid (so enrollment never repeats one).
export function pickSentence(mode, exclude = []) {
  const source = mode === "identify" ? CONFESSIONS : KNOWN_SAMPLES;
  const pool = source.filter((s) => !exclude.includes(s));
  return pool[Math.floor(Math.random() * pool.length)];
}
