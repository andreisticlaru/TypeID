// Two prompt pools, mirroring forensic authorship work: bland "known samples" to enrol from
// (and to verify against), and incriminating "questioned documents" to identify. The model only
// ever sees timing, so the content is there for the visitor: you get named by your rhythm while
// typing something you'd rather not own.
//
// Only the content differs between pools. The typing mechanics match the Aalto training sentences
// (sentence case, end punctuation, some names), because Shift is a real keystroke in both Aalto and
// live capture and its overlap with the next key is part of what the model learned. Lowercase
// prompts would drop that signal. 30-48 characters keeps each prompt above the 25-keystroke floor
// and inside one 50-keystroke window. Each prompt is ONE sentence (Aalto: 0.1% have two): a mid-prompt
// ". X" adds a sentence-boundary pause plus Shift that enrolment would never contain. Both pools keep
// commas near Aalto's 11% for the same reason: parity between pools matters more than style.

